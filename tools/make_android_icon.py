"""Writes the Android adaptive launcher icon (vector drawables) with the same design as the
Windows icon from make_icon.py: two cyan sync arrows on a dark background.

Usage: python tools/make_android_icon.py android/app/src/main/res/drawable
"""
import math
import os
import sys

# Same geometry as make_icon.py's large icon, on its 1024 px canvas
STROKE, RADIUS, HEAD_LEN, HEAD_W, GAP = 96, 300, 128, 118, 62
CANVAS = 1024
VIEWPORT = 108          # adaptive icon canvas (dp); the launcher mask keeps the middle ~66 dp
ARROW_SPAN = 60         # dp the arrows should span, inside the safe zone
SCALE = ARROW_SPAN / (2 * (RADIUS + 30))
C = VIEWPORT / 2


def pt(x, y):
    """1024-canvas coordinates centred on 0,0 -> viewport coordinates."""
    return f"{C + x * SCALE:.2f},{C + y * SCALE:.2f}"


def polar(r, deg):
    a = math.radians(deg)
    return r * math.cos(a), r * math.sin(a)


def arrow_path(start):
    end = start + 180 - GAP
    r_out, r_in = RADIUS, RADIUS - STROKE
    ro, ri = r_out * SCALE, r_in * SCALE
    large = 1 if end - start > 180 else 0
    p = [
        f"M{pt(*polar(r_out, start))}",
        f"A{ro:.2f},{ro:.2f} 0 {large} 1 {pt(*polar(r_out, end))}",
        f"L{pt(*polar(r_in, end))}",
        f"A{ri:.2f},{ri:.2f} 0 {large} 0 {pt(*polar(r_in, start))}",
        "Z",
    ]
    # Arrowhead at the clockwise end, pointing along the tangent (as in make_icon.py)
    rmid = RADIUS - STROKE / 2
    th = math.radians(end)
    px, py = rmid * math.cos(th), rmid * math.sin(th)
    tx, ty = -math.sin(th), math.cos(th)
    nx, ny = math.cos(th), math.sin(th)
    tip = (px + tx * HEAD_LEN, py + ty * HEAD_LEN)
    a = (px + nx * HEAD_W, py + ny * HEAD_W)
    b = (px - nx * HEAD_W, py - ny * HEAD_W)
    p += [f"M{pt(*tip)}", f"L{pt(*a)}", f"L{pt(*b)}", "Z"]
    return " ".join(p)


GRADIENT = """        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="{x0}" android:startY="{y0}"
                android:endX="{x1}" android:endY="{y1}">
                <item android:offset="0" android:color="{c0}" />
                <item android:offset="1" android:color="{c1}" />
            </gradient>
        </aapt:attr>"""

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_android_icon.py: edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""

out = sys.argv[1]
lo, hi = C - ARROW_SPAN / 2, C + ARROW_SPAN / 2

foreground = HEADER + f"""    <path android:pathData="{arrow_path(200)} {arrow_path(20)}">
{GRADIENT.format(x0=lo, y0=lo, x1=hi, y1=hi, c0="#FF00D4FF", c1="#FF58A6FF")}
    </path>
</vector>
"""

# Themed icons (Android 13+): the launcher tints this single-colour layer itself
monochrome = HEADER + f"""    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{arrow_path(200)} {arrow_path(20)}" />
</vector>
"""

background = HEADER + f"""    <path android:pathData="M0,0h108v108h-108z">
{GRADIENT.format(x0=0, y0=0, x1=108, y1=108, c0="#FF16202E", c1="#FF090D12")}
    </path>
</vector>
"""

with open(os.path.join(out, "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
    f.write(foreground)
with open(os.path.join(out, "ic_launcher_background.xml"), "w", encoding="utf-8") as f:
    f.write(background)
with open(os.path.join(out, "ic_launcher_monochrome.xml"), "w", encoding="utf-8") as f:
    f.write(monochrome)
print("ok")
